// plat_setjmp / plat_longjmp for Windows x64 (plat_jmp.h says why not ucrtbase's). Windows ABI: the buffer in rcx,
// the value in edx. Callee-saved: rbx rbp rdi rsi r12-r15, xmm6-xmm15, MXCSR control bits and the x87 control word.
// The shadow stack pointer is read with rdsspq, a no-op that leaves 0 in rax when CET is off or absent; longjmp pops
// the entries above the saved one plus setjmp's own return entry (glibc's ____longjmp_chk does the same).
#include "plat_jmp.h"

_Static_assert(sizeof(PlatJmpBuf) == 256 && __builtin_offsetof(PlatJmpBuf, ssp) == 88, "offsets in the assembly below");

__asm__(".text\n"
        ".globl plat_setjmp\n"
        ".p2align 4\n"
        "plat_setjmp:\n"
        "  movq (%rsp), %rdx\n"
        "  leaq 8(%rsp), %rax\n"
        "  movq %rbx, 0(%rcx)\n"
        "  movq %rbp, 8(%rcx)\n"
        "  movq %rdi, 16(%rcx)\n"
        "  movq %rsi, 24(%rcx)\n"
        "  movq %r12, 32(%rcx)\n"
        "  movq %r13, 40(%rcx)\n"
        "  movq %r14, 48(%rcx)\n"
        "  movq %r15, 56(%rcx)\n"
        "  movq %rax, 64(%rcx)\n"
        "  movq %rdx, 72(%rcx)\n"
        "  stmxcsr 80(%rcx)\n"
        "  fnstcw 84(%rcx)\n"
        "  movdqu %xmm6, 96(%rcx)\n"
        "  movdqu %xmm7, 112(%rcx)\n"
        "  movdqu %xmm8, 128(%rcx)\n"
        "  movdqu %xmm9, 144(%rcx)\n"
        "  movdqu %xmm10, 160(%rcx)\n"
        "  movdqu %xmm11, 176(%rcx)\n"
        "  movdqu %xmm12, 192(%rcx)\n"
        "  movdqu %xmm13, 208(%rcx)\n"
        "  movdqu %xmm14, 224(%rcx)\n"
        "  movdqu %xmm15, 240(%rcx)\n"
        "  xorl %eax, %eax\n"
        "  rdsspq %rax\n"
        "  movq %rax, 88(%rcx)\n"
        "  xorl %eax, %eax\n"
        "  ret\n"

        ".globl plat_longjmp\n"
        ".p2align 4\n"
        "plat_longjmp:\n"
        "  movq 88(%rcx), %r8\n"
        "  testq %r8, %r8\n"
        "  jz 3f\n"
        "  xorl %eax, %eax\n"
        "  rdsspq %rax\n"
        "  testq %rax, %rax\n"
        "  jz 3f\n"
        "  subq %rax, %r8\n"   // bytes between now and setjmp's ssp (the shadow stack grows down)
        "  shrq $3, %r8\n"
        "  addq $1, %r8\n"     // and setjmp's own return entry
        "1:\n"
        "  cmpq $255, %r8\n"
        "  jbe 2f\n"
        "  movl $255, %eax\n"
        "  incsspq %rax\n"
        "  subq $255, %r8\n"
        "  jmp 1b\n"
        "2:\n"
        "  incsspq %r8\n"
        "3:\n"
        "  ldmxcsr 80(%rcx)\n"
        "  fldcw 84(%rcx)\n"
        "  movdqu 96(%rcx), %xmm6\n"
        "  movdqu 112(%rcx), %xmm7\n"
        "  movdqu 128(%rcx), %xmm8\n"
        "  movdqu 144(%rcx), %xmm9\n"
        "  movdqu 160(%rcx), %xmm10\n"
        "  movdqu 176(%rcx), %xmm11\n"
        "  movdqu 192(%rcx), %xmm12\n"
        "  movdqu 208(%rcx), %xmm13\n"
        "  movdqu 224(%rcx), %xmm14\n"
        "  movdqu 240(%rcx), %xmm15\n"
        "  movq 0(%rcx), %rbx\n"
        "  movq 8(%rcx), %rbp\n"
        "  movq 16(%rcx), %rdi\n"
        "  movq 24(%rcx), %rsi\n"
        "  movq 32(%rcx), %r12\n"
        "  movq 40(%rcx), %r13\n"
        "  movq 48(%rcx), %r14\n"
        "  movq 56(%rcx), %r15\n"
        "  movl %edx, %eax\n"
        "  testl %eax, %eax\n"
        "  jnz 4f\n"
        "  movl $1, %eax\n"
        "4:\n"
        "  movq 64(%rcx), %rsp\n"
        "  jmpq *72(%rcx)\n");
